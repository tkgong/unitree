#!/usr/bin/env python3
"""Emit alu_mul31_p2.sv and alu_mul31_en_p2.sv: the 31 x 31 -> 62 multiplier as an explicit Dadda tree cut into two
pipeline stages so that each stage closes 1 ns in nangate45 (syn/README.md).
  stage 1: the 961 partial-product bits a[i] & b[j], reduced with full / half adders from 31 rows to STAGE_ROWS rows
           (Dadda heights 28, 19, 13, 9, 6, 4: 6 adder levels), registered (one flip-flop per surviving bit)
  stage 2: the remaining reduction to 2 rows (4 -> 3 -> 2: 2 levels), then one 62-bit carry-propagate add
The function is exactly a * b (verify/tb_alu.sv compares both modules with the reference, latency 2)."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
N = 31; OUT = 2 * N; STAGE_ROWS = 4
def dadda_heights(rows):
    h = [2]
    while h[-1] < rows: h.append(int(h[-1] * 3 // 2))
    return h[:-1][::-1]           # e.g. 31 rows: [28, 19, 13, 9, 6, 4, 3, 2]
def emit(en):
    name = "alu_mul31_en_p2" if en else "alu_mul31_p2"
    L = []; w = L.append
    w(f"// generated by gen_mul31_p2.py: 31 x 31 -> 62 multiplier, Dadda tree in two pipeline stages (latency 2, II = 1)")
    w(f"// stage 1: partial products + reduction to {STAGE_ROWS} rows (registered); stage 2: reduction to 2 rows + 62-bit add" + (" ; y = 0 when en = 0" if en else ""))
    w(f"module {name} (")
    w("    input  logic        clk,")
    if en: w("    input  logic        en,")
    w("    input  logic [30:0] a,\n    input  logic [30:0] b,\n    output logic [61:0] y\n);")
    # columns: list of wire names per bit weight
    cols = [[] for _ in range(OUT)]
    for i in range(N):
        for j in range(N):
            cols[i + j].append(f"pp[{i}][{j}]")
    w("    logic [30:0] pp [0:30];")
    w("    generate for (genvar i = 0; i < 31; i++) begin : g_pp\n        assign pp[i] = a[i] ? b : 31'd0;\n    end endgenerate")
    nid = [0]
    def fa(x, y_, z, col):                       # returns (sum name, carry name)
        s, c = f"s{nid[0]}", f"c{nid[0]}"; nid[0] += 1
        w(f"    logic {s}, {c}; assign {s} = {x} ^ {y_} ^ {z}; assign {c} = ({x} & {y_}) | ({x} & {z}) | ({y_} & {z});")
        return s, c
    def ha(x, y_, col):
        s, c = f"s{nid[0]}", f"c{nid[0]}"; nid[0] += 1
        w(f"    logic {s}, {c}; assign {s} = {x} ^ {y_}; assign {c} = {x} & {y_};")
        return s, c
    def reduce_to(cols, target):
        new = [[] for _ in range(OUT)]
        carries = [[] for _ in range(OUT + 1)]
        for k in range(OUT):
            bits = cols[k] + carries[k]; carries[k] = []
            while len(bits) > target:
                if len(bits) - target >= 2:
                    x, y_, z = bits[:3]; bits = bits[3:]; s, c = fa(x, y_, z, k)
                else:
                    x, y_ = bits[:2]; bits = bits[2:]; s, c = ha(x, y_, k)
                bits.append(s); carries[k + 1].append(c)
            new[k] = bits
        assert not carries[OUT], "carry out of the top column"
        return new
    heights = dadda_heights(N)
    w("    // ---- stage 1: reduction " + " -> ".join(str(h) for h in heights if h >= STAGE_ROWS) + " ----")
    for h in heights:
        if h < STAGE_ROWS: break
        cols = reduce_to(cols, h)
    # register every surviving bit
    nreg = sum(len(c) for c in cols)
    w(f"    // {nreg} flip-flops at the stage boundary")
    regs = [[] for _ in range(OUT)]
    for k in range(OUT):
        for m, bit in enumerate(cols[k]):
            r = f"q_{k}_{m}"; regs[k].append(r); w(f"    logic {r};")
    if en: w("    logic en_q;")
    w("    always_ff @(posedge clk) begin")
    for k in range(OUT):
        for m, bit in enumerate(cols[k]): w(f"        {regs[k][m]} <= {bit};")
    if en: w("        en_q <= en;")
    w("    end")
    cols = regs
    w("    // ---- stage 2: reduction " + " -> ".join(str(h) for h in heights if h < STAGE_ROWS) + ", then the carry-propagate add ----")
    for h in heights:
        if h < STAGE_ROWS: cols = reduce_to(cols, h)
    w("    logic [61:0] row0, row1;")
    for k in range(OUT):
        w(f"    assign row0[{k}] = {cols[k][0] if len(cols[k]) > 0 else chr(49)+chr(39)+'b0'};")
        w(f"    assign row1[{k}] = {cols[k][1] if len(cols[k]) > 1 else chr(49)+chr(39)+'b0'};")
    w("    logic [61:0] sum; assign sum = row0 + row1;")
    w("    always_ff @(posedge clk) y <= " + ("en_q ? sum : 62'd0;" if en else "sum;"))
    w("endmodule")
    open(os.path.join(HERE, name + ".sv"), "w", newline="\n").write("\n".join(L) + "\n")
    print(f"{name}.sv: {nid[0]} adders, {nreg} stage flip-flops, Dadda heights {heights}")
emit(False); emit(True)
